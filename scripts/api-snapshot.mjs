// Snapshot the public API surface of every package.
//
// The surface has moved fast — an extension point added here, an option made
// optional there, `defineConfig` tightened — and nothing has been guarding it.
// A signature change that nobody intended is the failure mode a 1.0 is supposed
// to make impossible, so it has to be visible in a diff before it is published.
//
// Reads the emitted `.d.ts`, which is what a consumer actually sees. Reading
// `src` instead would miss anything the declaration emit changes on the way out.
import { readFile, writeFile, readdir } from 'node:fs/promises'
import { join, resolve } from 'node:path'
import ts from 'typescript'

const repo = resolve(import.meta.dirname, '..')
const check = process.argv.includes('--check')

/** Every package, with the entry points its `exports` map publishes. */
async function entryPoints() {
  const out = []
  for (const dir of (await readdir(join(repo, 'packages'))).sort()) {
    const manifestPath = join(repo, 'packages', dir, 'package.json')
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'))
    for (const [subpath, target] of Object.entries(manifest.exports ?? {})) {
      if (subpath === './package.json') continue
      const types = typeof target === 'object' && target !== null ? target.types : undefined
      if (typeof types !== 'string') continue
      out.push({
        specifier: subpath === '.' ? manifest.name : `${manifest.name}/${subpath.slice(2)}`,
        file: join(repo, 'packages', dir, types)
      })
    }
  }
  return out
}

/** Collapse whitespace so formatting changes are not API changes. */
const normalise = text =>
  text
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/\/\/[^\n]*/g, '')
    .replace(/\s+/g, ' ')
    .trim()

function surfaceOf(file) {
  const program = ts.createProgram([file], {
    target: ts.ScriptTarget.Latest,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    skipLibCheck: true,
    noEmit: true
  })
  const source = program.getSourceFile(file)
  if (!source) throw new Error(`no declaration file at ${file}`)
  const checker = program.getTypeChecker()
  const moduleSymbol = checker.getSymbolAtLocation(source)
  if (!moduleSymbol) return []

  const lines = []
  for (const symbol of checker.getExportsOfModule(moduleSymbol)) {
    // Follow an alias to what it actually re-exports, so `export { x } from`
    // records the same thing a direct declaration would.
    const target = symbol.flags & ts.SymbolFlags.Alias ? checker.getAliasedSymbol(symbol) : symbol
    for (const declaration of target.getDeclarations() ?? []) {
      lines.push(`${symbol.getName()}  ${normalise(declaration.getText())}`)
    }
  }
  // Sorted, so a reordered source is not a diff.
  return [...new Set(lines)].sort()
}

let changed = 0
for (const { specifier, file } of await entryPoints()) {
  const surface = surfaceOf(file)
  const body =
    `# ${specifier}\n\n` +
    `${surface.length} export(s). Generated by \`pnpm api:snapshot\`; do not edit.\n\n` +
    surface.map(line => `- ${line}`).join('\n') +
    '\n'

  const target = join(repo, 'api', `${specifier.replace(/[@/]/g, '_')}.md`)
  if (check) {
    const existing = await readFile(target, 'utf8').catch(() => undefined)
    if (existing !== body) {
      changed++
      console.log(`CHANGED  ${specifier}`)
      if (existing === undefined) {
        console.log('         no snapshot on record for this entry point')
      } else {
        const before = new Set(existing.split('\n').filter(l => l.startsWith('- ')))
        const after = new Set(body.split('\n').filter(l => l.startsWith('- ')))
        for (const line of after) if (!before.has(line)) console.log(`    added   ${line.slice(2)}`)
        for (const line of before) if (!after.has(line)) console.log(`    removed ${line.slice(2)}`)
      }
    }
  } else {
    await writeFile(target, body, 'utf8')
    console.log(`wrote    api/${specifier.replace(/[@/]/g, '_')}.md  (${surface.length} exports)`)
  }
}

if (check) {
  if (changed === 0) {
    console.log('PASS  the public API matches its snapshot')
  } else {
    console.log(
      `\nFAIL  ${changed} entry point(s) changed. If the change is intended, run ` +
        '`pnpm api:snapshot` and commit the result — the diff is the review.'
    )
    process.exitCode = 1
  }
}
